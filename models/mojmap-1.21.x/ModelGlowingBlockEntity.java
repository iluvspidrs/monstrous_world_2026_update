	// the entity renderer and passed into this model's constructor
	public static final ModelLayerLocation LAYER_LOCATION = new ModelLayerLocation(
			new ResourceLocation("modid", "glowingblockentity"), "main");
	private final ModelPart glowingentity;

	public ModelGlowingBlockEntity(ModelPart root) {
		this.glowingentity = root.getChild("glowingentity");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition meshdefinition = new MeshDefinition();
		PartDefinition partdefinition = meshdefinition.getRoot();

		PartDefinition glowingentity = partdefinition.addOrReplaceChild("glowingentity", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-7.875F, -15.875F, -7.875F, 15.75F, 15.75F, 15.75F, new CubeDeformation(0.0F)),
				PartPose.offset(0.0F, 24.0F, 0.0F));

		return LayerDefinition.create(meshdefinition, 64, 64);
	}

